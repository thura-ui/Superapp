i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: initialLang,
    fallbackLng: 'en',
    supportedLngs: ['en', 'my'],
    interpolation: {
      escapeValue: false, // React တွင် XSS အတွက် အလိုအလျောက် ပံ့ပိုးပြီးဖြစ်သည်
    },
    detection: {
      order: ['localStorage', 'navigator'],
      caches: ['localStorage']
    }
  });

// 🌟 WebView / Web View တွင် Language ပြောင်းတိုင်း HTML Attribute နှင့် LocalStorage အား သေချာပေါက် Synchronize ပြုလုပ်ပေးမည့် Listener
i18n.on('languageChanged', (lng) => {
  const targetLang = lng.startsWith('my') ? 'my' : 'en';
  localStorage.setItem('language', targetLang);
  localStorage.setItem('i18nextLng', targetLang);
  document.documentElement.setAttribute('lang', targetLang);
  document.documentElement.lang = targetLang;
});

